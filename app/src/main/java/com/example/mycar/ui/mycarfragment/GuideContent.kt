fun articlesFor(section: GuideSection): List<GuideArticle> = when (section) {
    GuideSection.SYMPTOMS, GuideSection.LOCATION, GuideSection.URGENCY -> guideArticles.filter { it.section == GuideSection.SYMPTOMS }
    else -> guideArticles.filter { it.section == section }
}

private fun String.searchable() = lowercase(java.util.Locale.ROOT).replace('ё', 'е')

fun findGuideArticles(section: GuideSection, query: String, category: String = "Все"): List<GuideArticle> {
    val terms = query.searchable().trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
    return articlesFor(section).filter { article ->
        val facet = when (section) {
            GuideSection.LOCATION -> article.area
            GuideSection.URGENCY -> article.urgency.label
            else -> article.category
        }
        val text = listOf(article.title, article.summary, article.category, article.area,
            article.explanations.joinToString(" "), article.actions.joinToString(" "),
            article.avoid, article.serviceNote).joinToString(" ").searchable()
        (category == "Все" || facet == category) && terms.all { it in text }
    }
}
